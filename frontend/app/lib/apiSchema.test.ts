import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import type { Refinar, Schema } from "./apiSchema";
import type { MetaListItem } from "./metas";
import type { UserListItem } from "./users";

/**
 * #273 — os tipos de `app/lib/` vêm do schema OpenAPI do backend.
 *
 * As provas de tipo abaixo não rodam: quem as confere é o `tsc` (`npm run
 * typecheck`, no CI). Cada `@ts-expect-error` é um erro que PRECISA existir;
 * se o tipo gerado afrouxar e o erro sumir, a diretiva sobra e o `tsc` falha.
 */

const RAIZ = path.resolve(__dirname, "..", "..");
const SCHEMA = path.resolve(RAIZ, "..", "backend", "schema.yml");

/** Só para o `tsc` ter o que conferir; nunca é chamada. */
export function provasDeTipo(meta: MetaListItem, usuario: UserListItem) {
  // Campo que o backend não publica não existe no tipo: é o bug do "Estado"
  // vazio da issue, agora pego na compilação.
  // @ts-expect-error `estado` não existe em WorkPlanMetaList
  void meta.estado;
  // @ts-expect-error `nome` não existe em UserList (o campo é `nome_completo`)
  void usuario.nome;

  // O que o schema publica chega ao tipo de tela sem ser redeclarado.
  const executado: string = meta.valor_executado;
  const autor: { id: number; nome: string } | null = usuario.acesso_revogado_por;

  // Refinar só aceita campo que existe no tipo gerado: se o backend remover o
  // campo, o refinamento deixa de compilar em vez de inventá-lo.
  // @ts-expect-error `campo_que_nao_existe` não está em WorkPlanMetaList
  type Invalido = Refinar<Schema<"WorkPlanMetaList">, { campo_que_nao_existe: string }>;

  return [executado, autor, null as unknown as Invalido];
}

describe("tipos da API a partir do schema (#273)", () => {
  it("api-types.ts é o arquivo gerado, não uma cópia editada à mão", () => {
    const gerado = readFileSync(path.join(RAIZ, "app", "lib", "api-types.ts"), "utf8");
    expect(gerado).toContain("This file was auto-generated by openapi-typescript.");
    expect(gerado).toContain("export interface components");
  });

  // O schema fica em `backend/`, fora do contexto de um build só do frontend.
  it.skipIf(!existsSync(SCHEMA))("api-types.ts está em dia com backend/schema.yml", { timeout: 60_000 }, () => {
    const cli = path.join(RAIZ, "node_modules", "openapi-typescript", "bin", "cli.js");
    // Sai com código 1, e o teste falha, quando o arquivo commitado diverge do gerado.
    execFileSync(process.execPath, [cli, SCHEMA, "-o", "app/lib/api-types.ts", "--check"], {
      cwd: RAIZ,
      stdio: "pipe",
    });
  });
});
